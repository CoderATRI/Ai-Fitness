export function isLandmarkVisible(lm?: Landmark, minVisibility = 0.5): boolean {
  if (!lm) return false;
  return lm.visibility === undefined || lm.visibility >= minVisibility;
}

export function areKeyLandmarksVisible(
  landmarks: Landmark[],
  indices: number[],
  minVisibility = 0.4
): boolean {
  return indices.every((idx) => isLandmarkVisible(landmarks[idx], minVisibility));
}
